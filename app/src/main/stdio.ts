/**
 * Вывод процесса может быть закрыт: приложение запустили из терминала, который потом закрыли, или из лаунчера
 * с оборванным каналом. Тогда любой console.* бросает EPIPE — без обработчика это необработанное исключение,
 * а его обработчик сам пишет в консоль, и ошибки идут по кругу. Логи в закрытый вывод просто пропадают.
 */
export function ignoreClosedOutput() {
  for (const s of [process.stdout, process.stderr]) s?.on?.('error', () => {});
}
